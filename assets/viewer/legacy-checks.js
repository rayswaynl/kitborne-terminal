export function checklistKey(label, checklist) {
  if (Object.hasOwn(checklist, label)) return label;
  const legacy = LEGACY_CHECKS[label];
  if (legacy instanceof RegExp) return Object.keys(checklist).find(key => legacy.test(key)) ?? label;
  return legacy && Object.hasOwn(checklist, legacy) ? legacy : label;
}
